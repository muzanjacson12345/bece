const GENERATED_ID_RANGES = Object.freeze({
  mat: [101, 200],
  com: [101, 200],
  soc: [101, 200],
  art: [101, 200],
  rme: [115, 200],
  sci: [27, 200],
  fre: [1, 200],
  ct: [1, 200]
});

const GENERATED_CORRECT_KEY_BY_SUFFIX_MOD = Object.freeze(["A", "D", "C", "B"]);

export function getCorrectAnswer(questionId) {
  if (typeof questionId !== "string" || questionId.length > 40) return null;
  const fixed = FIXED_ANSWER_KEYS[questionId];
  if (fixed) return fixed;

  const match = /^(mat|com|soc|art|rme|sci|fre|ct)-(\\d{1,3})$/.exec(questionId);
  if (!match) return null;
  const range = GENERATED_ID_RANGES[match[1]];
  const number = Number(match[2]);
  if (!range || number < range[0] || number > range[1]) return null;
  return GENERATED_CORRECT_KEY_BY_SUFFIX_MOD[number % 4];
}

export function isCorrectAnswer(questionId, selectedKey) {
  if (typeof selectedKey !== "string" || !/^[A-D]$/.test(selectedKey)) return false;
  return getCorrectAnswer(questionId) === selectedKey;
}

export function isKnownQuestionId(questionId) {
  return getCorrectAnswer(questionId) !== null;
}

